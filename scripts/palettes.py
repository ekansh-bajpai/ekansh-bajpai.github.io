"""Colour theme for the portfolio (Nordic Slate; light + dark). Add entries to T to experiment with others. Run `python3 scripts/palettes.py` to regenerate palettes.css.
Each theme: light + dark; tokens: bg (page), surface (header, chips), card, line (borders), ink (text), muted,
accent (links, titles), cta / cta_hover (filled buttons, white text), hl (result badges), tab (active-tab underline)."""
T = {
 'nordic': ('Nordic Slate', {
   'light': dict(bg='#f8fafc', surface='#eef2f7', card='#ffffff', line='#d8dee9', ink='#2e3440', muted='#5e6a7e', accent='#4c6f99', cta='#4c6f99', cta_hover='#3e5c80', hl='#a54a54', tab='#bf616a'),
   'dark':  dict(bg='#2e3440', surface='#3b4252', card='#3b4252', line='#4c566a', ink='#eceff4', muted='#b4bccb', accent='#88c0d0', cta='#4c6f99', cta_hover='#3e5c80', hl='#ebcb8b', tab='#ebcb8b')}),
}
DEFAULT = 'nordic'

def rgb(h):
    h = h.lstrip('#'); return ' '.join(str(int(h[i:i + 2], 16)) for i in (0, 2, 4))
def block(sel, toks):
    return sel + ' {\n' + ''.join(f'  --{k.replace("_", "-")}: {rgb(v)};\n' for k, v in toks.items()) + '}\n'

if __name__ == '__main__':
    import json, os
    here = os.path.dirname(os.path.abspath(__file__))
    css = ['/* Generated by scripts/palettes.py: edit the table there, then re-run. Values are "R G B" for Tailwind opacity. */\n']
    for key, (_, modes) in T.items():
        light_sel = f':root[data-palette="{key}"]' + (', :root:not([data-palette])' if key == DEFAULT else '')
        dark_sel = f':root.dark[data-palette="{key}"]' + (', :root.dark:not([data-palette])' if key == DEFAULT else '')
        css += [block(light_sel, modes['light']), block(dark_sel, modes['dark'])]
    open(os.path.join(here, '..', 'palettes.css'), 'w').write('\n'.join(css))
    print('wrote palettes.css:', ', '.join(T))
